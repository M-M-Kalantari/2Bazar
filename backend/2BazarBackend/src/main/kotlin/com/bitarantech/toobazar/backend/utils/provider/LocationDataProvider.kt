    fun getData():
            Triple<
                    List<LocProvinceEntity>,
                    List<LocCityEntity>,
                    List<LocNeighborhoodEntity>
                    > {

        val provinces = mutableListOf<LocProvinceEntity>()
        val cities = mutableListOf<LocCityEntity>()
        val neighborhoods = mutableListOf<LocNeighborhoodEntity>()

        data.forEach { provinceData ->

            val province = LocProvinceEntity(
                name = provinceData.name
            )

            provinces.add(province)

            provinceData.cities.forEach { cityData ->

                val city = LocCityEntity(
                    name = cityData.name,
                    province = province
                )

                cities.add(city)

                cityData.neighborhoods.forEach { neighborhoodName ->

                    val neighborhood = LocNeighborhoodEntity(
                        name = neighborhoodName,
                        city = city
                    )

                    neighborhoods.add(neighborhood)
                }
            }
        }

        return Triple(
            provinces,
            cities,
            neighborhoods
        )
    }
